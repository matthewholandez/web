import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const projectRoot = process.cwd();
const contentDirectory = path.join(projectRoot, "content", "explanations");
const outputDirectory = path.join(projectRoot, "app", "generated");
const outputPath = path.join(outputDirectory, "explanation-loaders.ts");
const slugPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

const entries = await readdir(contentDirectory, { withFileTypes: true });
const slugs = entries
  .filter((entry) => entry.isFile() && entry.name.endsWith(".md"))
  .map((entry) => entry.name.slice(0, -3))
  .sort();

const invalidSlug = slugs.find((slug) => !slugPattern.test(slug));

if (invalidSlug) {
  throw new Error(
    `Explanation filename "${invalidSlug}.md" must use lowercase words separated by hyphens.`,
  );
}

const loaders = slugs
  .map(
    (slug) =>
      `  "${slug}": () => import("@/content/explanations/${slug}.md"),`,
  )
  .join("\n");

const source = `// Generated by scripts/generate-explanations.mjs. Do not edit by hand.
export const explanationLoaders = {
${loaders}
} as const;

export type ExplanationSlug = keyof typeof explanationLoaders;
`;

await mkdir(outputDirectory, { recursive: true });
await writeFile(outputPath, source);
